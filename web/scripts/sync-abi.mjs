// Regenerates lib/abi.ts from the Foundry artifact. Run after every contract change (CLAUDE.md §8).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../../contracts/out/BlindBidMarket.sol/BlindBidMarket.json");
const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
const out = resolve(here, "../lib/abi.ts");
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/sync-abi.mjs from contracts/out — do not edit.\n` +
    `export const blindBidMarketAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`wrote ${out} (${abi.length} entries)`);
